import fs from 'node:fs';
fs.mkdirSync('probe-out', { recursive: true });
const H = { 'user-agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/130 Safari/537.36', accept: 'application/json, text/plain, */*' };
const log = [];
const save = async (name, u) => { try { const r = await fetch(u, { headers: H }); const t = await r.text(); fs.writeFileSync('probe-out/' + name, t); log.push(`${name} ${r.status} ${t.length} ${t.slice(0, 150).replace(/\s+/g, ' ')}`); } catch (e) { log.push(`${name} ERR ${e.message}`); } };
const d = new Date().toISOString().slice(0, 10).replace(/-/g, '');
await save('an_nba_v1.json', `https://api.actionnetwork.com/web/v1/scoreboard/nba?period=game&bookIds=15,30,68,69,75&date=${d}`);
await save('an_nba_v2.json', `https://api.actionnetwork.com/web/v2/scoreboard/nba?bookIds=15,30&date=${d}&periods=event`);
await save('an_soccer_v1.json', `https://api.actionnetwork.com/web/v1/scoreboard/soccer?period=game&bookIds=15,30&date=${d}`);
await save('an_ncaab_v1.json', `https://api.actionnetwork.com/web/v1/scoreboard/ncaab?period=game&bookIds=15,30&date=${d}`);
await save('nesine_populer.html', 'https://www.nesine.com/iddaa/en-cok-oynananlar');
await save('misli_populer.html', 'https://www.misli.com/iddaa/en-cok-oynananlar');
fs.writeFileSync('probe-out/log.txt', log.join('\n'));
